CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS applicant_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    label VARCHAR(50) NOT NULL,
    CONSTRAINT uq_profile_label UNIQUE (user_id, label),
    CONSTRAINT uq_profile_owner UNIQUE (user_id, id)
);

CREATE TABLE IF NOT EXISTS profile_answer (
    profile_id BIGINT NOT NULL REFERENCES applicant_profile(id) ON DELETE CASCADE,
    attribute_key VARCHAR(100) NOT NULL,
    answer_value VARCHAR(50) NOT NULL,
    PRIMARY KEY (profile_id, attribute_key)
);

CREATE TABLE IF NOT EXISTS assessment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    profile_id BIGINT NOT NULL,
    scheme_slug VARCHAR(70) NOT NULL,
    scheme_title VARCHAR(150) NOT NULL,
    rule_version INTEGER NOT NULL,
    verdict VARCHAR(24) NOT NULL CHECK (verdict IN ('MATCH', 'NEEDS_INFO', 'NO_MATCH', 'OUTSIDE_SCOPE')),
    result_json CLOB NOT NULL,
    assessed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_assessment_owner FOREIGN KEY (user_id, profile_id)
        REFERENCES applicant_profile(user_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_assessment_user ON assessment (user_id, id DESC);
